function setLanguage(language) {
  const dict = translations[language] || translations.en;
  document.documentElement.lang = language;
  const menuButton = document.querySelector(".menu-button");
  if (menuButton) menuButton.setAttribute("aria-label", dict.menu);
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (dict[key]) element.textContent = dict[key];
  });
  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.lang === language));
  });
  document.querySelector('meta[name="description"]').setAttribute(
    "content",
    language === "pt-BR"
      ? "Serviços de psicologia clínica com foco em adultos no espectro autista. Conheça os atendimentos, as modalidades e como entrar em contato."
      : "Clinical psychology services with a focus on autistic adults. Learn about the services, appointment formats, and how to make contact."
  );
  document.title = language === "pt-BR"
    ? "Psicologia Clínica | Atendimento a Adultos no Espectro Autista"
    : "Clinical Psychology | Support for Autistic Adults";
  sessionStorage.setItem("preferred-language", language);
}

document.querySelectorAll("[data-lang]").forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
});

const menuButton = document.querySelector(".menu-button");
const siteNav = document.querySelector(".site-nav");
menuButton.addEventListener("click", () => {
  const open = menuButton.getAttribute("aria-expanded") === "true";
  menuButton.setAttribute("aria-expanded", String(!open));
  siteNav.classList.toggle("open", !open);
});
siteNav.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", () => {
    menuButton.setAttribute("aria-expanded", "false");
    siteNav.classList.remove("open");
  });
});

const toast = document.querySelector(".toast");
document.querySelectorAll(".contact-pending").forEach((button) => {
  button.addEventListener("click", () => {
    const language = document.documentElement.lang;
    toast.textContent = language === "pt-BR"
      ? "Este dado ainda precisa ser confirmado pelo profissional."
      : "This detail still needs to be confirmed by the professional.";
    toast.hidden = false;
    window.clearTimeout(toast.timer);
    toast.timer = window.setTimeout(() => { toast.hidden = true; }, 4000);
  });
});

setLanguage(sessionStorage.getItem("preferred-language") || "en");
